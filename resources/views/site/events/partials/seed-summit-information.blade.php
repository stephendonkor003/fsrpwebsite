        </div>

        <div class="seed-summit-audience">
            <div>
                <span class="resource-category">Who will take part</span>
                <h3>A continental leadership and investment platform</h3>
            </div>
            <p>Heads of State, Ministers responsible for Agriculture, seed-sector government officials, farmer organisations, private-sector seed industry representatives, agricultural researchers, seed experts and development agencies.</p>
        </div>

        <div class="seed-summit-priority-grid">
            <article class="seed-summit-priority-card">
                <span class="seed-summit-card-number">01</span>
                <div>
                    <p class="resource-category">Summit objectives</p>
                    <h3>Turn political commitment into coordinated action</h3>
                    <ul>
                        <li>Consider the Ezulwini Declaration on Africa’s seed systems.</li>
                        <li>Mobilise consistent, sustainable public investment in Africa’s seed sector.</li>
                        <li>Unlock investment opportunities and co-investment in country-led seed-system transformation.</li>
                        <li>Strengthen legal and regulatory environments that encourage private investment.</li>
                        <li>Launch the Seed Sector Performance Index 2025 Status Report for Africa.</li>
                    </ul>
                </div>
            </article>

            <article class="seed-summit-priority-card seed-summit-priority-card-gold">

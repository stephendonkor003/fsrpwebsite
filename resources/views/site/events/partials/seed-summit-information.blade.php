                    <h3>Commitments that can be monitored and delivered</h3>
                    <ul>
                        <li>The Ezulwini Declaration on Africa’s seed systems.</li>
                        <li>Public-sector financing and private-sector investment commitments and deals.</li>
                        <li>Heads of State commitments to stronger enabling policy and regulatory environments.</li>
                        <li>Launch and endorsement of the SSPI 2025 Status Report as an AU monitoring tool under the CAADP Biennial Review framework.</li>
                    </ul>
                </div>
            </article>
        </div>

